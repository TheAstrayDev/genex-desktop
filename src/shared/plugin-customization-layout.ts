/** Declarative host surfaces, grids and widgets. No selectors, executable markup or network requests. */
/** Stable host anchors, without access to selectors or DOM nodes. */
export const CustomizationSlot = {
  App: "app",
  Sidebar: "sidebar",
  Workspace: "workspace",
  NewChat: "newChat",
  Profile: "profile",
  Navigation: "navigation",
} as const;
/** One host-owned destination for a surface or widget grid. */
export type CustomizationSlot = (typeof CustomizationSlot)[keyof typeof CustomizationSlot];
/** Native navigation actions whose grid placement can change. */
export const CustomizationItem = {
  NewGame: "newGame",
  Plugins: "plugins",
  Harness: "harness",
  Settings: "settings",
} as const;
/** An existing navigation action, never a plugin-supplied click handler. */
export type CustomizationItem = (typeof CustomizationItem)[keyof typeof CustomizationItem];
/** Built-in displays and an isolated panel for custom interactive widgets. */
export const CustomizationWidgetKind = {
  Text: "text",
  Clock: "clock",
  Weather: "weather",
  Image: "image",
  Panel: "panel",
} as const;
/** Background renderers generated by the host from validated data. */
export const CustomizationBackgroundKind = {
  Solid: "solid",
  Gradient: "gradient",
  Glow: "glow",
  Image: "image",
} as const;
/** Color-based paint or embedded raster data, without remote URLs or SVG. */
export type CustomizationBackground =
  | { kind: "solid"; color: string }
  | { kind: "gradient"; colors: string[]; angle: number; animated: boolean }
  | { kind: "glow"; colors: string[]; animated: boolean }
  | { kind: "image"; data: string; animated: boolean };
/** A bounded 1-based position in a host grid. */
export interface CustomizationPlacement {
  column: number;
  row: number;
  columnSpan: number;
  rowSpan: number;
}
/** Widget columns and spacing, plus native navigation placement at its own anchor. */
export interface CustomizationLayout {
  target: CustomizationSlot;
  columns: number;
  gap: number;
  items: Partial<Record<CustomizationItem, CustomizationPlacement & { height?: number }>>;
}
/** A declarative widget; panel references belong to the declaring plugin. */
export interface CustomizationWidget extends CustomizationPlacement {
  id: string;
  target: CustomizationSlot;
  kind: "text" | "clock" | "weather" | "image" | "panel";
  label: string;
  text: string;
  image?: string;
  panel?: string;
}
/** Canonical host composition removed as one layer on disable or reset. */
export interface CustomizationComposition {
  surfaces: Partial<Record<CustomizationSlot, CustomizationBackground>>;
  layout: CustomizationLayout[];
  widgets: CustomizationWidget[];
}
const MAX_IMAGE_CHARS = 1_400_000;
const MAX_TOTAL_IMAGE_CHARS = 2_800_000;
const MAX_WIDGETS = 12;
const MAX_LABEL = 80;
const MAX_TEXT = 240;
const MAX_ROWS = 24;
const MAX_COLUMNS = 12;
const MESSAGE = { Invalid: "Invalid UI customization composition" } as const;
/** Parse a plain record with exactly the allowed keys. */
function record(value: unknown, keys: readonly string[]): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error(MESSAGE.Invalid);
  const prototype = Object.getPrototypeOf(value);
  const plain = prototype === Object.prototype || prototype === null;
  if (!plain || Object.keys(value).some((key) => !keys.includes(key))) throw new Error(MESSAGE.Invalid);
  return value as Record<string, unknown>;
}
function number(value: unknown, fallback: number, min: number, max: number): number {
  if (value === undefined) return fallback;
  if (typeof value !== "number" || !Number.isInteger(value) || value < min || value > max)
    throw new Error(MESSAGE.Invalid);
  return value;
}
function string(value: unknown, max: number): string {
  if (value === undefined) return "";
  if (typeof value !== "string" || value.length > max || [...value].some((character) => character.charCodeAt(0) < 9))
    throw new Error(MESSAGE.Invalid);
  return value;
}
function color(value: unknown): string {
  if (typeof value !== "string" || value.length !== 7 || !/^#[0-9a-f]{6}$/i.test(value))
    throw new Error(MESSAGE.Invalid);
  return value.toLowerCase();
}
function image(value: unknown): string {
  const data = string(value, MAX_IMAGE_CHARS);
  const encoded = data.slice(data.indexOf(",") + 1);
  const valid =
    data.trim() === data &&
    encoded.length % 4 === 0 &&
    /^data:image\/(?:png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$/.test(data);
  if (!valid) throw new Error(MESSAGE.Invalid);
  return data;
}
function animated(value: unknown): boolean {
  if (value === undefined) return false;
  if (typeof value !== "boolean") throw new Error(MESSAGE.Invalid);
  return value;
}
function background(value: unknown): CustomizationBackground {
  const raw = record(value, ["kind", "color", "colors", "angle", "animated", "data"]);
  if (raw.kind === CustomizationBackgroundKind.Solid) {
    record(value, ["kind", "color"]);
    return { kind: raw.kind, color: color(raw.color) };
  }
  if (raw.kind === CustomizationBackgroundKind.Image) {
    record(value, ["kind", "data", "animated"]);
    return { kind: raw.kind, data: image(raw.data), animated: animated(raw.animated) };
  }
  const gradient = raw.kind === CustomizationBackgroundKind.Gradient;
  if (!gradient && raw.kind !== CustomizationBackgroundKind.Glow) throw new Error(MESSAGE.Invalid);
  record(value, gradient ? ["kind", "colors", "angle", "animated"] : ["kind", "colors", "animated"]);
  if (!Array.isArray(raw.colors) || raw.colors.length < 2 || raw.colors.length > 4) throw new Error(MESSAGE.Invalid);
  if (!gradient)
    return { kind: CustomizationBackgroundKind.Glow, colors: raw.colors.map(color), animated: animated(raw.animated) };
  return {
    kind: CustomizationBackgroundKind.Gradient,
    colors: raw.colors.map(color),
    angle: number(raw.angle, 135, 0, 360),
    animated: animated(raw.animated),
  };
}
function slot(value: unknown): CustomizationSlot {
  const result = Object.values(CustomizationSlot).find((known) => known === value);
  if (!result) throw new Error(MESSAGE.Invalid);
  return result;
}
function placement(
  raw: Partial<Record<keyof CustomizationPlacement, unknown>>,
  columns = MAX_COLUMNS,
): CustomizationPlacement {
  const column = number(raw.column, 1, 1, columns);
  const row = number(raw.row, 1, 1, MAX_ROWS);
  const columnSpan = number(raw.columnSpan, 1, 1, columns);
  const rowSpan = number(raw.rowSpan, 1, 1, MAX_ROWS);
  if (column + columnSpan - 1 > columns || row + rowSpan - 1 > MAX_ROWS) throw new Error(MESSAGE.Invalid);
  return { column, row, columnSpan, rowSpan };
}
function layout(value: unknown): CustomizationLayout {
  const raw = record(value, ["target", "columns", "gap", "items"]);
  const columns = number(raw.columns, 1, 1, MAX_COLUMNS);
  const items = record(raw.items ?? {}, Object.values(CustomizationItem));
  const parsed: CustomizationLayout["items"] = {};
  for (const key of Object.values(CustomizationItem)) {
    if (!Object.hasOwn(items, key)) continue;
    const item = record(items[key], ["column", "row", "columnSpan", "rowSpan", "height"]);
    parsed[key] = {
      ...placement(item, columns),
      ...(item.height === undefined ? {} : { height: number(item.height, 40, 24, 160) }),
    };
  }
  const target = slot(raw.target);
  if (target !== CustomizationSlot.Navigation && Object.keys(parsed).length) throw new Error(MESSAGE.Invalid);
  return { target, columns, gap: number(raw.gap, 8, 0, 48), items: parsed };
}
function widget(value: unknown): CustomizationWidget {
  const raw = record(value, [
    "id",
    "target",
    "kind",
    "label",
    "text",
    "image",
    "panel",
    "column",
    "row",
    "columnSpan",
    "rowSpan",
  ]);
  const id = string(raw.id, 40);
  if (id.trim() !== id || !/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(MESSAGE.Invalid);
  const kind = Object.values(CustomizationWidgetKind).find((known) => known === raw.kind);
  if (!kind) throw new Error(MESSAGE.Invalid);
  if (kind !== CustomizationWidgetKind.Image && raw.image !== undefined) throw new Error(MESSAGE.Invalid);
  if (kind !== CustomizationWidgetKind.Panel && raw.panel !== undefined) throw new Error(MESSAGE.Invalid);
  const panel = string(raw.panel, MAX_LABEL);
  if (kind === CustomizationWidgetKind.Panel && !panel) throw new Error(MESSAGE.Invalid);
  return {
    id,
    target: slot(raw.target),
    kind,
    label: string(raw.label, MAX_LABEL),
    text: string(raw.text, MAX_TEXT),
    ...placement({ ...raw, columnSpan: raw.columnSpan ?? 3, rowSpan: raw.rowSpan ?? 6 }),
    ...(kind === CustomizationWidgetKind.Image ? { image: image(raw.image) } : {}),
    ...(kind === CustomizationWidgetKind.Panel ? { panel } : {}),
  };
}
/** Validate bounded surfaces and grid entries without evaluating CSS, HTML or provider code. */
export function parseCustomizationComposition(raw: Record<string, unknown>): CustomizationComposition {
  const surfaces = record(raw.surfaces ?? {}, Object.values(CustomizationSlot));
  const parsed: CustomizationComposition["surfaces"] = {};
  for (const target of Object.values(CustomizationSlot))
    if (Object.hasOwn(surfaces, target)) parsed[target] = background(surfaces[target]);
  const layouts = raw.layout ?? [];
  const widgets = raw.widgets ?? [];
  if (!Array.isArray(layouts) || layouts.length > Object.keys(CustomizationSlot).length)
    throw new Error(MESSAGE.Invalid);
  if (!Array.isArray(widgets) || widgets.length > MAX_WIDGETS) throw new Error(MESSAGE.Invalid);
  const result = { surfaces: parsed, layout: layouts.map(layout), widgets: widgets.map(widget) };
  const imageChars =
    Object.values(parsed).reduce(
      (total, surface) => total + (surface.kind === CustomizationBackgroundKind.Image ? surface.data.length : 0),
      0,
    ) + result.widgets.reduce((total, entry) => total + (entry.image?.length ?? 0), 0);
  if (imageChars > MAX_TOTAL_IMAGE_CHARS) throw new Error(MESSAGE.Invalid);
  if (new Set(result.layout.map((entry) => entry.target)).size !== result.layout.length)
    throw new Error(MESSAGE.Invalid);
  if (new Set(result.widgets.map((entry) => entry.id)).size !== result.widgets.length) throw new Error(MESSAGE.Invalid);
  for (const entry of result.widgets) {
    const columns = result.layout.find((grid) => grid.target === entry.target)?.columns ?? MAX_COLUMNS;
    placement(entry, columns);
  }
  return result;
}
